function getCCSPath(name)
	local CURRENT_CCSFILE_PATH = "ccsFiles"
	if SoraDGetLayoutAlignment() == gLayoutAlignmentTypeDef.right then
		CURRENT_CCSFILE_PATH = "ccsFiles"
	else
		CURRENT_CCSFILE_PATH = "ccsFiles_en"
	end
	if nametopath[name] then
		if ccsFilesOnly[name] then
			return "ccsFiles" .. nametopath[name] .. ".csb"
		elseif ccsFilesEnOnly[name] then
			return "ccsFiles_en" .. nametopath[name] .. ".csb"
		end
		return CURRENT_CCSFILE_PATH .. nametopath[name] .. ".csb"
	end
	if commonPath[name] then
		return "ccsCommonFiles" .. commonPath[name] .. ".csb"
	end
	if newResPath[name] then
		return "commonLogin/" .. CURRENT_CCSFILE_PATH .. newResPath[name] .. ".csb"
	end
	return nil
end
function getCCSPathTable()
	return nametopath
end
function getCommonPathTable()
	return commonPath
