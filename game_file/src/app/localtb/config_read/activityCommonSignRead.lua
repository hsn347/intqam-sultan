activityCommonSignRead:defineValue("common_sign_in_reward", function()
	local config = require_data("common_sign_in_reward", true, true).data
	local _ENV, ret = "common_sign_in_reward", "common_sign_in_reward"
	for __, v in ipairs(config) do
		local ActivityId = v.ActivityId
		local rewardType = v.rewardType
		if not ret[ActivityId] then
			_ENV = ret[ActivityId]
		end
		ret[ActivityId] = ret[ActivityId]
		if not ret[ActivityId][rewardType] then
			_ENV = ret[ActivityId][rewardType]
		end
		ret[ActivityId][rewardType] = ret[ActivityId][rewardType]
		v.day = v.id
		table.insert(ret[ActivityId][rewardType], v)
	end
	return ret
end)
function activityCommonSignRead.getRewardConfig(activityID, rewardType)
	rewardType = rewardType or SoraDGetCtrl("activityShowCtrl"):getParamClassType(activityID)
	local config = activityCommonSignRead.common_sign_in_reward[activityID]
	if not config or not config[rewardType] then
		_ENV = config[rewardType]
	end
	return config[rewardType]
end
function activityCommonSignRead.getCumuDayArray(activityID, rewardType)
	local _ENV, ret
	for k, v in ipairs(activityCommonSignRead.getRewardConfig(activityID, rewardType)) do
		if next(v.cumulateReward) then
			table.insert(ret, v.day)
		end
	end
	return ret
end
function activityCommonSignRead.getAwardByDay(activityID, day)
	local config = activityCommonSignRead.getRewardConfig(activityID)
	local cfg = config[day]
	if not cfg or not cfg.normalReward then
		local activityCommonSignRead, rewards = cfg.normalReward, cfg.normalReward
	end
	_UPVALUE2_ = nil
