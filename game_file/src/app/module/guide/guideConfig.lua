function guideConfig.getNextGuideStep(curGuideStep)
	if curGuideStep and guideStepConfig[curGuideStep] then
		return guideStepConfig[curGuideStep].nextGuideStep
	end
end
function guideConfig.getGuideModule(guideStep)
	if guideStep and guideStepConfig[guideStep] then
		return guideStepConfig[guideStep].guideModule
	end
end
function guideConfig.getViewStep(guideStep, trigger)
	local cfg = guideStep and guideStepConfig[guideStep]
	if cfg then
		if trigger and cfg["viewStep" .. trigger] then
			return cfg["viewStep" .. trigger]
		end
		return cfg.viewStep
	end
end
function guideConfig.checkGuideStepNeedJump(guideStep)
	local cfg = guideStep and guideStepConfig[guideStep]
	if cfg and cfg.needJump then
		return true
	else
		return false
	end
end
function guideConfig.transformGuideStep(viewStep)
	if viewStep and transformGuideStepConfig[viewStep] then
		return transformGuideStepConfig[viewStep]
	end
end
function guideConfig.isForceToGuide(guideStep)
	if guideStep and guideStepConfig[guideStep] then
		local guildModule = guideStepConfig[guideStep].guideModule
		if guildModule then
			return guideModuleConfig[guildModule].isForce
		end
	end
end
function guideConfig.getGuidePriority(guideStep)
	if guideStep and guideStepConfig[guideStep] then
		local guildModule = guideStepConfig[guideStep].guideModule
		if guildModule then
			return guideModuleConfig[guildModule].priority
		end
	end
end
function guideConfig.getGuideBeginStep(guideModule)
	if guideModule and guideModuleConfig[guideModule] then
		return guideModuleConfig[guideModule].beginStep
	end
end
return guideConfig
