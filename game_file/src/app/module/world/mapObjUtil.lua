function mapObjUtil.getBuildName(instanceType, subMapType, objId)
	local name
	if gMapObjTypeDef.mapObjTypeBattlefieldSite == instanceType then
		name = worldMapDefine.getPyramidbuildingName(subMapType)
	elseif gMapObjTypeDef.mapObjTypeAllianceBuild == instanceType then
		local allianceDesRead = include("allianceDesRead")
		name = allianceDesRead.getBuildName(subMapType)
	elseif gMapObjTypeDef.mapObjTypeBattery == instanceType then
		local palaceInfoRead = include("palaceInfoRead")
		name = palaceInfoRead.getBatteryName(objId)
	elseif instanceType == gMapObjTypeDef.mapTypeRadianceWarPalace or instanceType == gMapObjTypeDef.mapTypeRadianceWarGate or instanceType == gMapObjTypeDef.mapTypeRadianceWarBeacon then
		local radianceWarRead = include("radianceWarRead")
		name = radianceWarRead.getBuildName(instanceType, objId)
	elseif instanceType == gMapObjTypeDef.mapTypeRadianceWarResource then
		local radianceWarRead = include("radianceWarRead")
		name = radianceWarRead.getResourceName(subMapType)
	elseif instanceType == gMapObjTypeDef.nebulaWarBuilding then
		local nebulaWarRead = include("nebulaWarRead")
		name = nebulaWarRead.getBuildName(subMapType)
	elseif instanceType == gMapObjTypeDef.mapObjTypeLegendLord and worldMapDefine.isKingStarMapId(worldMapDefine.currentMapKindomID) then
		name = i18n("kingstarbattle_text_64")
	elseif instanceType == gMapObjTypeDef.nebulaEmperorWarBuilding then
		local nebulaEmperorRead = include("nebulaEmperorRead")
		name = nebulaEmperorRead.getBuildName(subMapType) or nebulaEmperorRead.getBuildNameByType(subMapType)
	elseif instanceType == gMapObjTypeDef.nebulaAllStarWarBuilding then
		if subMapType == gWorldTypeServerDef.subTypeNebulaAllStarViewerSpoil then
			name = i18n("NebulaAllstar_154")
		else
			local nebulaAllStarRead = include("nebulaAllStarRead")
			name = nebulaAllStarRead.getBuildName(subMapType) or nebulaAllStarRead.getBuildNameByType(subMapType)
		end
	elseif instanceType == gMapObjTypeDef.nebulaDefenceWarBuilding then
		local activity_9001573_Read = include("activity_9001573_Read")
		name = activity_9001573_Read.getBuildName(objId and objId or subMapType)
	elseif instanceType == gMapObjTypeDef.mapObjTypeKingdomLevelBuild then
		name = i18n("common_text_3957")
	elseif instanceType == gMapObjTypeDef.bubbleLandParty then
		name = i18n("activity_name_9001500")
	elseif instanceType == gMapObjTypeDef.bubbleLandGift then
		local activity_9001670_Read = include("activity_9001670_Read")
		name = activity_9001670_Read.getGiftName(subMapType or 1)
	elseif instanceType == gMapObjTypeDef.fantasyLandParty then
		name = i18n("activity_name_9001500")
	elseif instanceType == gMapObjTypeDef.fantasyLandGift then
		local activity_9001717_Read = include("activity_9001717_Read")
		name = activity_9001717_Read.getGiftName(subMapType or 1)
	elseif instanceType == gMapObjTypeDef.roaringFlameWarBuilding then
		local roaringFlameWarRead = include("roaringFlameWarRead")
		subMapType = subMapType or roaringFlameWarRead.getBuildSubType(objId)
		name = roaringFlameWarRead.getBuildName(subMapType)
	elseif instanceType == gMapObjTypeDef.simulatedDrillWarBuilding then
		local simulatedDrillRead = include("simulatedDrillRead")
		name = simulatedDrillRead.getBuildName(subMapType)
	elseif instanceType == gMapObjTypeDef.mapTypeAtlantisWarBuilding then
		local atlantisActivityRead = include("atlantisActivityRead")
		name = atlantisActivityRead.getBuildName(subMapType)
	else
		local str = mapObjUtil.getTargetBuildName(instanceType, subMapType)
		if str then
			name = i18n(str)
		end
	end
	name = name or i18n("buildDes_name_101")
	return name
end
