local genInstanceID = function(x, y, instanceType, subMapType, objId)
	x = x + gPointClientPointPlus
	y = y + gPointClientPointPlus
	return string.format("%d-%d-%d-%d-%d", x, y, instanceType, subMapType or 0, objId or 0)
end
local genLocalInstanceData = function(x, y, instanceType, subMapType, objId, objData, key)
	if not objData then
		objData, genInstanceID = nil, nil
	end
	local genInstanceID, mapObj
	local id = genInstanceID(x, y, instanceType, subMapType, objId)
	mapObj.id = id
	local kingdomMapUtil = include("kingdomMapUtil")
	kingdomMapUtil.splitMapObjId(mapObj)
	mapObj.id = key or id
	mapObj.isLocal = true
	local instanceFactory = include("instanceFactory")
	local dataKey = instanceFactory.getInstanceDataKey(instanceType)
	if dataKey then
		mapObj[dataKey] = objData
	end
	return mapObj
end
function mapObjUtil.createLocalInstance(x, y, instanceType, subMapType, objId, objData, key)
	local mapObjData = genLocalInstanceData(x, y, instanceType, subMapType, objId, objData, key)
	genLocalInstanceData = y
	y.msg = "MESSAGE_SERVER_WORLD_MAP_INSTANCE_ADD"
	_ENV, y.isLocal = instanceType, true
	y.data, instanceType[1] = instanceType, mapObjData
	SoraDSendMessage(y)
end
function mapObjUtil.removeLocalInstance(x, y, instanceType, subMapType, objId, objData, key)
	local mapObjData = genLocalInstanceData(x, y, instanceType, subMapType, objId, objData, key)
	genLocalInstanceData = y
	y.msg = "MESSAGE_SERVER_WORLD_MAP_INSTANCE_REMOVE"
	_ENV, y.isLocal = instanceType, true
	y.data, instanceType[1] = instanceType, mapObjData
	SoraDSendMessage(y)
end
