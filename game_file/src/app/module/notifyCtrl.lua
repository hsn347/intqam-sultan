local notifyMsgConfig
local gameModule = include("GameModule")
local serverproxy = gModuleMgr.getObject("serverproxy")
local gametop = gModuleMgr.getObject("gametop")
local msgCtrl = include("msgCtrl")
local notifyCtrl = class("notifyCtrl", gameModule)
local requireNotify = function(self, notifyID, ...)
end
local notifyRsp = function(self, content)
	if content.err == gErrDef.Err_None then
		local notifyID = content.data.notifyID
		notifyID = tostring(notifyID)
		local status, err = xpcall(function()
			self = nil
			;(nil).name = notifyID
			;(nil).data = content.data.notifyData
			self:dispatchEvent(nil)
		end, __G__TRACKBACK__)
		if not status then
		end
		requireNotify(self, notifyID)
	end
end
local registerMsg = function(self)
	for id, msg in pairs(notifyMsgConfig) do
		msgCtrl.register(msg.cmd, msg.subcmd, handler(self, notifyRsp))
	end
end
function notifyCtrl:ctor(properties)
	notifyCtrl.super.ctor(self, properties)
end
function notifyCtrl:EnterGame()
	notifyCtrl.super.EnterGame(self)
	registerMsg(self)
	self:register(gNotifyID.COMMON, handler(self, self.commonRsp))
end
function notifyCtrl:resetData()
end
function notifyCtrl:Logout()
	notifyCtrl.super.Logout(self)
	self:resetData()
end
function notifyCtrl:commonRsp(event)
	local data = event.data
	for i, notifyMsg in ipairs(data) do
		local notifyType = notifyMsg.notifyType
		if "allyRepatriated" == notifyType then
			local nickname = notifyMsg.nickname
			_ENV = nil
			;(nil).name = nickname
			include("msgNotice").notice("common_text_2858", nil)
		elseif "newDay" == notifyType then
			_ENV = include("msgNotice").notice
			include("msgNotice").notice.msg = "MESSAGE_MAINSCEN_NEWDAY"
			SoraDSendMessage(include("msgNotice").notice)
		elseif "otherMassSlaveRecall" == notifyType then
			local nickname = notifyMsg.nickname
			local itemID = notifyMsg.itemId
			local publicRead = include("publicRead")
			local itemIcon = publicRead.getIcon(itemID)
			_ENV = nil
			;(nil).name = nickname
			SoraDShowMsgTip(i18n("common_text_4561", nil), "#" .. itemIcon)
		elseif "selfMassSlaveRecall" == notifyType then
			local itemID = notifyMsg.itemId
			local publicRead = include("publicRead")
			local itemIcon = publicRead.getIcon(itemID)
			SoraDShowMsgTip(i18n("common_text_4560"), "#" .. itemIcon)
		end
	end
end
function notifyCtrl:register(notifyID, listener)
	if "string" ~= type(notifyID) or "function" ~= type(listener) or notifyMsgConfig[notifyID] == nil then
		return
	end
	assert("string" == type(notifyID), "the notifyID is not a stirng!")
	assert("function" == type(listener), "the listener is not a function!")
	assert(notifyMsgConfig[notifyID], "the notifyID doesn't config!")
	local handle = self:addEventListener(notifyID, listener)
	requireNotify(self, notifyID)
	return handle
end
function notifyCtrl:removeNotify(handle)
	if not handle then
		return
	end
	self:removeEventListener(handle)
end
function notifyCtrl:logout(notifyID)
	if not notifyID then
		return
	end
	notifyID = tostring(notifyID)
	if self.removeEventListenersByEvent then
		self:removeEventListenersByEvent(notifyID)
	elseif self.removeAllEventListenersForEvent then
		self:removeAllEventListenersForEvent(notifyID)
	end
end
return notifyCtrl
