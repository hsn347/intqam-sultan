function sultansBackView:onExitPanel()
	if self.lastShowTabIndex then
		_ENV = nil
		;(nil).byUID = true
		SoraDConfigSet("Game:sultansBackView:lastShowTabIndex~integer", self.lastShowTabIndex, nil)
	end
end
function sultansBackView:ctor(properties)
	self.activityID = gActivityCenterUIEnum.SULTAN_BACK
	self.activityNodeTable, _ENV, self.newFlagList, _ENV, self.redPointList, _ENV, self.tabItemList, _ENV, self.itemSize = cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120), cc.size(130, 120)
	self.bottomPanel = SoraDGetChildByName(self, "Panel_Bottom_Size")
	self.scrollItems = SoraDGetChildByName(self, "Top_ScrollView_items")
	self.buttonItem = SoraDGetChildByName(self, "Button_item")
	self.nodeCommonFramTitle = SoraDGetExtendChildFromCCSByName(self, "Top_CCS_commonFramTitle_node")
	self.nodeCommonFramTitle:setTitle(i18n("activity_name_9001289"))
	self.btnSetting = SoraDGetChildByName(self.nodeCommonFramTitle, "Button_Setting")
	self.btnSetting:addTouchEventListener(handler(self, self.btnSettingClick))
	self:initScrollTab()
end
function sultansBackView:onMessageListener()
	SoraDAddMessage(self, "MESSAGE_SERVER_EVENTCENTER_COMMONEVENT_REFRESH", handler(self, self.msgCallBack))
	SoraDAddMessage(self, "MESSAGE_SERVER_EVENT_COMMON_RED_POINT_REFRESH", handler(self, self.updateRedPoint))
	SoraDAddMessage(self, "MESSAGE_UI_EVENTCENTER_REFRESHISNEW", handler(self, self.updateNewFlag))
end
function sultansBackView:initScrollTab()
	self.showTab = self:getShowTab()
	if table.nums(self.showTab) == 0 then
		SoraDRemoveAllAfterPanelFromManager(self)
		return
	end
	local singleW = self.itemSize.width * #self.showTab
	local scrollH = math.max(self.scrollItems:getContentSize().width, singleW)
	self.scrollItems:setInnerContainerSize(cc.size(scrollH, self.scrollItems:getContentSize().height))
	for index, _ in ipairs(btnConfig) do
		if self.tabItemList[index] then
			self.tabItemList[index]:setVisible(false)
		end
	end
	for i, value in ipairs(self.showTab) do
		local buttonItem
		if self.tabItemList[value.index] then
			buttonItem = self.tabItemList[value.index]
			buttonItem:setVisible(true)
		else
			buttonItem = self.buttonItem:clone()
			buttonItem:addTo(self.scrollItems)
			buttonItem:addTouchEventListener(handler(self, self.btnItemClick))
			buttonItem:setTag(value.index)
			if not buttonItem.etNode then
				buttonItem.etNode = SoraDCreatAnimation("animationCZLBS")
				buttonItem.etNode:addTo(buttonItem:getChildByName("Node_effect"))
			end
			SoraDGetChildByName(buttonItem, "Text_item"):setString(i18n(btnConfig[value.index].btnName))
			SoraDGetChildByName(buttonItem, "Sprite_item"):setSpriteFrame(btnConfig[value.index].btnSpirte)
			self.tabItemList[value.index] = buttonItem
			self.redPointList[value.index] = SoraDGetChildByName(buttonItem, "Sprite_redPoint")
			self.newFlagList[value.index] = SoraDGetChildByName(buttonItem, "Sprite_New")
		end
		local posX = (i - 0.5) * self.itemSize.width
		if SoraDFIsRA() then
			posX = scrollH - posX
		end
		buttonItem:setPosition(posX, self.itemSize.height / 2 + 9)
		self.newFlagList[value.index]:setVisible(value.isNew)
		self.redPointList[value.index]:setVisible(value.redNum ~= 0)
		self.redPointList[value.index]:getChildByName("Text_redNum"):setString(value.redNum)
		self:setItemUnselect(value.index)
		local text = self.redPointList[value.index]:getChildByName("Text_redNum")
		if 0 < value.redNum then
			text:setVisible(true)
			text:setString(value.redNum)
		else
			text:setVisible(false)
		end
	end
	self:switchMode(self:getShowTabIndex())
end
function sultansBackView:switchMode(showTabIndex)
	if self.lastShowTabIndex == showTabIndex then
		return
	end
	self:setItemSelect(showTabIndex)
	if self.lastShowTabIndex then
		self:setItemUnselect(self.lastShowTabIndex)
	else
		self:jumpToChooseItem(showTabIndex)
	end
	self.lastShowTabIndex = showTabIndex
	if btnConfig[showTabIndex].ccsName then
		local node = self.activityNodeTable[showTabIndex]
		if not node then
			node = SoraDCreatePanel(btnConfig[showTabIndex].ccsName)
			node:addTo(self.bottomPanel)
			node:setPosition(0, 0)
			self.activityNodeTable[showTabIndex] = node
			if node.setParentView then
				node:setParentView(self)
			end
			node:initData()
		end
		if node.reqInitData then
			node:reqInitData()
		end
	end
end
function sultansBackView:btnItemClick(target, eventType)
	if eventType == ccui.TouchEventType.ended then
		SoraDPlaySound()
		local showTabIndex = target:getTag()
		self:switchMode(showTabIndex)
	end
end
function sultansBackView:btnSettingClick(target, eventType)
	if eventType == ccui.TouchEventType.ended then
		SoraDPlaySound()
		SoraDCreatePanel("sultansBackSettingPop"):show()
	end
end
function sultansBackView:msgCallBack(target, redata)
	if type(redata.activityID) == "table" then
		for _, v in pairs(redata.activityID) do
			if v == gActivityCenterUIEnum.SULTAN_BACK then
				self:checkActivityStatus()
			end
		end
	elseif type(redata.activityID) == "number" and v == gActivityCenterUIEnum.SULTAN_BACK then
		self:checkActivityStatus()
	end
end
function sultansBackView:checkActivityStatus()
	if not clientEventMgr.judgeIsOpen(self.activityID) then
		SoraDRemoveAllAfterPanelFromManager(self)
	else
		if self.lastShowTabIndex then
			_ENV = nil
			;(nil).byUID = true
			SoraDConfigSet("Game:sultansBackView:lastShowTabIndex~integer", self.lastShowTabIndex, nil)
			self.lastShowTabIndex = nil
		end
		self:initScrollTab()
	end
end
function sultansBackView:updateRedPoint(target, data)
	dump(data, "updateRedPoint", 10)
	local activityID = data.activityID or data.eventID
	local redNode = self:getRedNodeByActivityID(activityID)
	if redNode then
		local redNum = sultansBackCtrl:getRednumByActivityID(activityID)
		redNode:setVisible(redNum ~= 0)
		local text = redNode:getChildByName("Text_redNum")
		if 0 < redNum then
			text:setVisible(true)
			text:setString(redNum)
		else
			text:setVisible(false)
		end
	end
end
function sultansBackView:updateNewFlag(target, data)
	if not data.removeNew then
		return
	end
	local activityID = data.eid
	local newFlagNode = self:getNewFlagByActivityID(activityID)
	if newFlagNode then
		newFlagNode:setVisible(false)
	end
end
function sultansBackView:getShowTab()
	local _ENV, showActivityIDList
	for index, v in ipairs(btnConfig) do
		if v.activityID and clientEventMgr.judgeIsOpen(v.activityID) and (not v.checkCastleLv or not (SoraDGetCastleLv() < v.checkCastleLv)) then
			local _ENV, single = SoraDGetCastleLv(), SoraDGetCastleLv()
			single.index = index
			single.isNew = activityCenterUICtrl:isHaveNewFlag(v.activityID)
			single.redNum = sultansBackCtrl:getRednumByActivityID(v.activityID)
			single.activityID = v.activityID
			table.insert(showActivityIDList, single)
		end
	end
	table.sort(showActivityIDList, function(l, r)
		if l.redNum > 0 == (r.redNum > 0) then
			if l.isNew == r.isNew then
				return l.index < r.index
			else
				return l.isNew
			end
		else
			return l.redNum > 0
		end
	end)
	return showActivityIDList
end
function sultansBackView:getShowTabIndex()
	_ENV = nil
	;(nil).byUID = true
	local showTabIndex = SoraDConfigGet("Game:sultansBackView:lastShowTabIndex~integer", nil)
	if not showTabIndex or btnConfig[showTabIndex] and btnConfig[showTabIndex].activityID and not clientEventMgr.judgeIsOpen(btnConfig[showTabIndex].activityID) then
		showTabIndex = self.showTab[1].index
	end
	if showTabIndex < 1 or showTabIndex > #btnConfig then
		showTabIndex = 1
	end
	return showTabIndex
end
function sultansBackView:jumpToChooseItem(showTabIndex)
	local sortIndex = self:getSorIndex(showTabIndex)
	self.scrollItems:jumpToPercentHorizontal(SoraDFPosX(math.max(0, 100 - math.max(0, sortIndex - 4) * 34), 100))
end
function sultansBackView:setItemSelect(index)
	if self.activityNodeTable[index] then
		self.activityNodeTable[index]:setVisible(true)
	end
	local itemNode = self.tabItemList[index]
	itemNode:getChildByName("Sprite_down"):setSpriteFrame("frame_cz_labelbg_02.png")
	itemNode:getChildByName("Text_item"):setColor(cc.c3b(255, 249, 214))
	itemNode:getChildByName("frame_select"):setVisible(true)
	itemNode:getChildByName("Node_effect"):setVisible(true)
end
function sultansBackView:setItemUnselect(index)
	if self.activityNodeTable[index] then
		self.activityNodeTable[index]:setVisible(false)
	end
	local itemNode = self.tabItemList[index]
	itemNode:getChildByName("Sprite_down"):setSpriteFrame("frame_cz_labelbg_03.png")
	itemNode:getChildByName("Text_item"):setColor(cc.c3b(151, 146, 134))
	itemNode:getChildByName("frame_select"):setVisible(false)
	itemNode:getChildByName("Node_effect"):setVisible(false)
end
function sultansBackView:getSorIndex(index)
	for i, v in ipairs(self.showTab) do
		if v.index == index then
			return i
		end
	end
end
function sultansBackView:getRedNodeByActivityID(activityID)
	for i, v in ipairs(btnConfig) do
		if v.activityID == activityID then
			return self.redPointList[i]
		end
	end
end
function sultansBackView:getNewFlagByActivityID(activityID)
	for i, v in ipairs(btnConfig) do
		if v.activityID == activityID then
			return self.newFlagList[i]
		end
	end
end
return sultansBackView
