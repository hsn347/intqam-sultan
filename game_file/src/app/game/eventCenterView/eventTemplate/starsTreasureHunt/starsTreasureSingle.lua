local publicRead = include("publicRead")
local starTreasureHuntRead = include("starTreasureHuntRead")
local starTreasureHuntCtrl = SoraDGetCtrl("starTreasureHuntCtrl")
local starsTreasureSingle = class("starsTreasureSingle", function(target)
	if target and tolua.type(target) == "string" then
		target = SoraDCreateBasePanel(target)
	end
	return target or SoraDCreateBasePanel("starsTreasureSingle")
end)
function starsTreasureSingle:ctor(properties)
	self.nodeEffect1 = SoraDGetChildByName(self, "Node_Effect_xyxb03_001")
	self.nodeEffect1:setVisible(false)
	self.nodeEffect2 = SoraDGetChildByName(self, "Node_Effect_xyxb03_002")
	self.nodeEffect2:setVisible(false)
	self.nodeEffect3 = SoraDGetChildByName(self, "Node_Effect_xyxb01_003")
	self.nodeEffect3:setVisible(false)
	self.spBg = SoraDGetChildByName(self, "dh_Tex_xyxb_004")
	self.spBg:setOpacity(0)
	self.spIcon = SoraDGetChildByName(self, "Image_icon")
	self.spIcon:setOpacity(0)
	self.btnItem = SoraDGetChildByName(self, "Button_Item")
	self.btnItem = include("commonBtnInstance").new(self.btnItem)
	self.spCzhl = SoraDGetChildByName(self, "icon_czhl_g")
	self.spCzhl:setOpacity(0)
	self.dh_14new1_02 = SoraDGetChildByName(self, "dh_14new1_02_17")
	self.dh_14new1_02:setOpacity(0)
	self:initEffect()
end
function starsTreasureSingle:initEffect()
	local loop = false
	local cssFileName = "starsTreasureSingle"
	local cssFilePath = getCCSPath(cssFileName)
	self.action = cc.CSLoader:createTimeline(cssFilePath)
	self.action:gotoFrameAndPause(0)
	self:runAction(self.action)
	SoraDMixtureGLONEByParent(self)
	local dh_14new1_02 = SoraDGetChildByName(self, "dh_14new1_02_17")
	dh_14new1_02:stopAllActions()
	dh_14new1_02:setRotation(0)
	dh_14new1_02:runAction(cc.RepeatForever:create(cca.rotateBy(1.4166666666666667, 360)))
end
