function starsTreasureSingle:initData(target, data)
	self.itemId = data.itemid
	self.position = data.position
	self.btnItem:setItemInfo(target, data.itemid, data.count)
	self.spIcon:setSpriteFrame(publicRead.getIcon(data.itemid))
	if data.position == 12 then
		self.dh_14new1_02:setVisible(true)
		self.dh_14new1_02:setRotation(0)
		self.dh_14new1_02:runAction(cc.RepeatForever:create(cca.rotateBy(1.4166666666666667, 360)))
	else
		self.dh_14new1_02:setVisible(false)
	end
	self:updateSingleStatus()
end
function starsTreasureSingle:updateSingleStatus()
	local isGet = starTreasureHuntCtrl:itemIsLock(self.itemId)
	self.spCzhl:setVisible(isGet)
	self.dh_14new1_02:setVisible(not isGet and self.position == 12)
	self.spIcon:setColor(isGet and cc.c3b(123, 123, 123) or cc.c3b(255, 255, 255))
end
return starsTreasureSingle
