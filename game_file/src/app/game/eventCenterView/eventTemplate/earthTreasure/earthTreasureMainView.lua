function earthTreasureMainView:updateGiftNode()
	self.curGiftID = earthTreasureCtrl:getCurGiftIndex()
	if self.curGiftID > 0 then
		self:showGiftNode()
		self.nodeGift:setVisible(true)
		local endTime = earthTreasureCtrl:getGiftTimeOut()
		if 0 < endTime then
