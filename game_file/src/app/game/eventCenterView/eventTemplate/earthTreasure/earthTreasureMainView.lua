function earthTreasureMainView:createAwardNode()
	local radius = 247
	for i, v in ipairs(earthTreasureRead.getRewardList(earthTreasureCtrl:getRewardGroup())) do
		local single = self.nodeSingle:clone()
		single:setVisible(true)
		single:addTo(self.centerNode)
		single:setScale(0.95)
		SoraDGetChildByName(single, "Image_icon"):loadTexture(publicRead.getIcon(v.rewards[1]), ccui.TextureResType.plistType)
		single:getChildByName("icon_czhl_g"):setVisible(false)
		local angle = math.angle2radian((i - 1) * 30 + 15)
		single:setPosition(math.sin(angle) * radius, math.cos(angle) * radius)
		if i == 1 then
			self.xuanzhong:setPosition(math.sin(angle) * radius, math.cos(angle) * radius + 16)
		end
		self:showQualityEffect(single, qualityColor[include("itemDesRead").getQuality(v.rewards[1])])
		table.insert(self.awardNodeList, single)
	end
end
