function commonChatBg:updateTheme()
	print("commonChatBg:updateTheme()------------------")
	if gCurrentChatTheme == gChatTheme.normal then
		self.node_night:setVisible(false)
	else
		self.node_night:setVisible(true)
	end
end
function commonChatBg:msgThemeChanged(target, data)
	self:updateTheme()
end
function commonChatBg:setContentHeight(height)
	SoraDGetChildByName(self, "Top_bg_1"):setPositionY(height)
	SoraDGetChildByName(self, "Size_Tile_Bg_3"):setContentSize(cc.size(641, height - 330))
end
