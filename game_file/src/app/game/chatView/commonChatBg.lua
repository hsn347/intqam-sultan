	self.sprite_smallToBig_0 = SoraDGetChildByName(self, "Sprite_smallToBig_0")
	self.node_night = SoraDGetChildByName(self, "Node_night")
	self.img_Bg:loadTexture("bg_chat_night_ar.png", ccui.TextureResType.plistType)
	self.img_Bg:setScale9Enabled(false)
	self.img_Bg:setColor(cc.c3b(255, 255, 255))
	if display.size.height > 1200 then
		self.img_Bg:setScaleY(display.size.height / self.img_Bg:getContentSize().height)
	end
	self:starShine()
end
function commonChatBg:onMessageListener()
