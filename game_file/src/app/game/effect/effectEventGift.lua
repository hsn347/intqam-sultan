function effectEventGift.getGiftNode(eType)
	print("eType=======", eType)
	local giftNode = display.newNode()
	if eType > CITEINDEX then
		local cssFilePath = effectEventGift.getCCSName("gift_effect_node_cite")
		giftNode = cc.uiloader:load(cssFilePath)
		local activeBtnTB = effectEventGift.gCiteImgType[eType]
		if activeBtnTB then
			local Sprite_static = SoraDGetChildByName(giftNode, "Sprite_static")
			Sprite_static:setSpriteFrame(activeBtnTB.png)
			if activeBtnTB.scale then
				Sprite_static:setScale(activeBtnTB.scale)
			end
			if activeBtnTB.posY then
				giftNode:setPositionY(activeBtnTB.posY - 100)
			end
			if activeBtnTB.posX then
				giftNode:setPositionX(activeBtnTB.posX)
			end
		end
	elseif eType > NEWCITEINDEX and eType < CITEINDEX then
		local ownType = math.floor(eType / NEWCITEINDEX)
		local cssFilePath = effectEventGift.getCCSName("gift_effect_node_cite_" .. ownType)
		giftNode = cc.uiloader:load(cssFilePath)
		local action = cc.CSLoader:createTimeline(cssFilePath)
		action:gotoFrameAndPlay(0, true)
		giftNode:runAction(action)
		local activeBtnTB = effectEventGift.gCiteImgType[eType]
		if activeBtnTB then
			local Sprite_static = SoraDGetChildByName(giftNode, "Sprite_static")
			Sprite_static:setSpriteFrame(activeBtnTB.png)
			if activeBtnTB.posY then
				giftNode:setPositionY(activeBtnTB.posY - 100)
			end
			if activeBtnTB.posX then
				giftNode:setPositionX(activeBtnTB.posX)
			end
		end
	else
		local ret = false
		for k, v in pairs(gActivityType) do
			if v == eType then
				ret = true
				break
			end
		end
		local realETpye = ret and eType or gActivityType.FESTIVAL_GIFT
		local cssFilePath = effectEventGift.getCCSName("gift_effect_node_" .. realETpye)
		giftNode = cc.uiloader:load(cssFilePath)
		local action = cc.CSLoader:createTimeline(cssFilePath)
		action:gotoFrameAndPlay(0, true)
		giftNode:runAction(action)
		local getResetTarget = function()
			local _ENV, array
			for k, v in ipairs(giftNode:getChildren()) do
				local nameTB = SoraDStringSplit(v:getName(), "_")
				if nameTB[#nameTB] == "reset" then
					table.insert(array, v)
				end
			end
			return array
		end
		local frameEventTargets = getResetTarget()
		if frameEventTargets and next(frameEventTargets) then
			action:setFrameEventCallFunc(function(frameEventName)
				local frameEvent = frameEventName:getEvent()
				if frameEvent then
					if frameEvent == "stop" then
						for k, v in ipairs(frameEventTargets) do
							if v.stopSystem then
								v:stopSystem()
							end
						end
					elseif frameEvent == "reset" then
						for k, v in ipairs(frameEventTargets) do
							if v.resetSystem then
								v:resetSystem()
							end
						end
					end
				end
			end)
		end
		local actConfig = effectEventGift.gCiteImgType[realETpye]
		giftNode:setPositionY(70)
		if actConfig then
			if actConfig.posX then
				giftNode:setPositionX(actConfig.posX)
			end
			if actConfig.posY then
				giftNode:setPositionY(actConfig.posY - 100)
			end
			if actConfig.scale then
				giftNode:setScale(actConfig.scale)
			end
			if actConfig.c3bPath then
				local c3bModel = cc.Sprite3D:create(actConfig.c3bPath)
				if c3bModel then
					_ENV = nil
					;(nil).x = 0
					;(nil).y = 0
					;(nil).z = 0
					c3bModel:setRotation3D(nil)
					local node3d = SoraDGetChildByName(giftNode, "Node_3d")
					c3bModel:addTo(node3d)
					local animation = cc.Animation3D:create(actConfig.c3bPath)
					if animation then
						local animate = cc.Animate3D:create(animation)
						c3bModel:runAction(cc.RepeatForever:create(animate))
					end
				end
			end
			if actConfig.spine then
				do
					local nodeSpine = SoraDGetChildByName(giftNode, "Node_Spine")
					local spine = sp.SkeletonAnimation:create("spine/" .. actConfig.spine .. ".skel", "spine/" .. actConfig.spine .. ".atlas", 1)
					spine:setAnimation(0, "animation", true)
					spine:addTo(nodeSpine)
				end
			end
		end
	end
	return giftNode
end
return effectEventGift
