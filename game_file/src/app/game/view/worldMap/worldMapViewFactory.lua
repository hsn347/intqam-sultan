local tbViewClass = "worldMapLodCfg"
function worldMapViewFactory.new(param)
	local kingdomID = worldMapDefine.currentMapKindomID
	local mapClassType = worldMapDefine.getKingdomMapClassByKingdomId(kingdomID)
	local config = tbViewClass[mapClassType] or "worldMapViewNormal"
	config.mapClassType = mapClassType
	if mapClassType == gKingdomClassType.atlantis then
		local atlantisWarUtil = include("atlantisWarUtil")
		if atlantisWarUtil.isNewMap() then
			config.tileMapTmx = config.tileMapTmx_KOH
			config.terrainControl = config.terrainControl_KOH
			config.createCustomLayer = config.createCustomLayer_KOH
		end
	end
	if config.configLod then
		local isLodOpen = true
		if config.canSwitch then
			isLodOpen = worldMapUtil.isLodOpen()
		end
		config.noScaleLimit = isLodOpen
	end
	if device.platform == "mac" or userSDKManager and (userSDKManager.isBeta() or userSDKManager.isReportError() or userSDKManager.isGameDevelop()) then
		config = clone(config)
		table.insert(config.comTable, "worldMapComDebugInfo")
	end
	local worldMapView = include("worldMapView").new(config, param)
	return worldMapView
end
return worldMapViewFactory
