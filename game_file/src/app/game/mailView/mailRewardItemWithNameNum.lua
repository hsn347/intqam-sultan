local publicRead = include("publicRead")
local mailRewardItemWithNameNum = class("mailRewardItemWithNameNum", function(target)
	return ccui.Layout:create()
end)
function mailRewardItemWithNameNum:ctor()
	self:setContentSize(cc.size(gMailDetaiViewWidth, 100))
	self:setSwallowTouches(false)
	self:setCascadeOpacityEnabled(true)
	self.itemBox = include("commonItemAward").new()
	self.itemBox:setCascadeOpacityEnabled(true)
	self.itemBox:addTo(self)
	self.itemBox:setPosition(cc.p(SoraDFPosX(550, gMailDetaiViewWidth), 50))
	self.itemBox:setOwnView(SoraDCurrentTopPanelFromManager())
	self.itemBox:setScale(0.8)
	self.itemName = ccui.Text:create()
	self.itemName:addTo(self)
	self.itemName:setColor(cc.c3b(105, 58, 21))
	self.itemName:setFontSize(20)
	self.itemName:setAnchorPoint(SoraDFPoint(1, 0.5, 1))
	self.itemName:setPosition(SoraDFPosX(490, gMailDetaiViewWidth), 50)
	self.itemNum = ccui.Text:create()
	self.itemNum:addTo(self)
	self.itemNum:setColor(cc.c3b(105, 58, 21))
	self.itemNum:setFontSize(20)
	self.itemNum:setAnchorPoint(SoraDFPoint(0, 0.5, 1))
	self.itemNum:setPosition(SoraDFPosX(60, gMailDetaiViewWidth), 50)
	self.spriteLine = display.newScale9Sprite("#frame_yjyh_line_02.png", gMailDetaiViewWidth / 2, 0, cc.size(563, 6), cc.rect(146, 0, 159, 6))
	self.spriteLine:addTo(self)
	self.itemWidth = gMailDetaiViewWidth
	self.itemHeight = 100
end
function mailRewardItemWithNameNum:initWithData(data)
	local num = data.num or data.count
	self.itemBox:initData(data.id, num)
	self.itemBox:setUpVisible(data.showUp)
	self.itemBox:setTouchEnabled(true)
	self.itemNum:setString(string.formatnumberthousands(num))
	self.itemName:setString(i18n(publicRead.getName(data.id)))
	self.spriteLine:setVisible(not data.hideLine)
end
return mailRewardItemWithNameNum
