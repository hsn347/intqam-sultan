		self:notifyStepEnd()
	end
end
function mainCityGuide:delayTime(param)
	self:stopActionByTag(DELAY_TAG)
	_ENV = self
	self[1] = cca.delay(param)
	self[2] = cca.callFunc(function()
		self:notifyStepEnd()
	end)
	self[3] = cca.callFunc(function()
		self:notifyStepEnd()
	end)
	local action = cca.seq(self)
	action:setTag(DELAY_TAG)
	self:runAction(action)
end
