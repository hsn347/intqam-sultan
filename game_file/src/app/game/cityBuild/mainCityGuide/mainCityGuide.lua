function mainCityGuide:showBubbleAni(param, ...)
	local bubble = self.guideManager:getTopTips(param)
	bubble:setVisible(true)
	local playAniEnd
	if bubble:getBubbleType() == "chuizi" then
		SoraDPlaySound("innerbuildsound", 204)
		local build = self.guideManager:getNode(bubble.data.param.name)
		local buildEntity = SoraDGetChildByName(build, "buildName")
		buildEntity:showAnimBuildWorker(false)
		buildEntity:hideZAnimation()
		local buildImg = SoraDGetChildByName(build, "buildImg")
		local oldSpFrame = buildImg:getSpriteFrame()
		buildImg:setSpriteFrame(bubble.data.param.image)
		function playAniEnd()
			buildEntity:setBlockState("building")
			buildEntity:changeState()
			buildImg:setSpriteFrame(oldSpFrame)
			bubble:setVisible(false)
			self:notifyStepEnd()
		end
	else
		function playAniEnd()
			if bubble:getBubbleType() == "juma" then
				bubble = nil
				;(nil).res = "dh_mczl_bz"
				;(nil).loop = false
				;(nil).count = 24
				;(nil).pos = cc.p(bubble:getPositionX(), bubble:getPositionY() - 50)
				;(nil).noNotify = true
				self:showEffect(nil)
				self.mainCityView:addResCollectAnimation(gIDDef.WOOD, cc.p(bubble:getPosition()), bubble, 2)
			elseif bubble:getBubbleType() == "liangshi" then
				self.mainCityView:addResCollectAnimation(gIDDef.FOOD, cc.p(bubble:getPosition()), bubble, 2)
			end
			bubble:setVisible(false)
			self:notifyStepEnd()
		end
	end
	if bubble:getBubbleType() == "zhiliao" then
		SoraDPlaySound("innerbuildsound", 206)
	elseif bubble:getBubbleType() == "juzi" or bubble:getBubbleType() == "juma" or bubble:getBubbleType() == "xiufu" then
		SoraDPlaySound("innerbuildsound", 204)
	elseif bubble:getBubbleType() == "liangshi" then
		SoraDPlaySound("trainsoilder", 201)
	end
	bubble:playAnimation(playAniEnd)
end
