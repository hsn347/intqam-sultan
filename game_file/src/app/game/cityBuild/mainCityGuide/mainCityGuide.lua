function mainCityGuide:onBubbleClick(param, bubble)
	if param.type == "juji" then
		SoraDPlaySound("worldmap", 2)
		bubble:setVisible(false)
		_ENV = nil
		;(nil).sceneType = bubble.data.param.sceneType
		;(nil).closeCallback = function(isWin)
			if isWin then
				self:notifyStepEnd()
			else
				self = "maincity_guide_" .. bubble.data.param.step
				;("maincity_guide_" .. bubble.data.param.step).result = 0
				userSDKManager.logEvent(gSDKDef.TDonEvent["maincity_guide_" .. bubble.data.param.step], "maincity_guide_" .. bubble.data.param.step)
				self = gSDKDef.TDonEvent["maincity_guide_" .. bubble.data.param.step]
				gSDKDef.TDonEvent["maincity_guide_" .. bubble.data.param.step].msg = "MESSAGE_MAINCITYGUIDE_STEPBACK"
				SoraDSendMessage(gSDKDef.TDonEvent["maincity_guide_" .. bubble.data.param.step])
			end
		end
		uiManager:show("SneakSnipeGame", nil)
	elseif param.type == "juzi" or param.type == "juma" then
		self:notifyStepEnd()
	elseif param.type == "liangshi" then
		self:notifyStepEnd()
	elseif param.type == "zhaomu" or param.type == "duihua" or param.type == "zhiliao" or param.type == "miwu" or param.type == "xiufu" or param.type == "gongji" or param.type == "chuizi" then
		self:notifyStepEnd()
	end
end
function mainCityGuide:showEffect(param)
	local sp = self.guideManager:createEffectSp(param.res, param.count, param.loop, param.remove == nil and true or param.remove)
	if param.posItem then
		local item = self.guideManager:getNode(param.posItem)
		if item then
			sp:setPosition(item:getPosition())
		else
			print("======== showEffect item not found", param.posItem)
			sp:removeFromParent()
		end
	else
		sp:setPosition(param.pos)
	end
	if param.res == "dh_mczl_bz" then
		SoraDPlaySound("epicWar", 1)
	end
	if not param.noNotify then
		self:notifyStepEnd()
	end
end
