local DELAY_TAG = 199
function mainCityGuide:ctor()
end
function mainCityGuide:initData(mainCityView, mainCityGuideStep, isNeedFirstFight)
	self.mainCityView = mainCityView
	self.startStep = mainCityGuideStep
	self.guideManager = include("MainCityGuideManager")
	self.parentNode = SoraDGetChildByName(self, "TopTips")
	self.roleParentNode = SoraDGetChildByName(self, "Roles")
	self.night = SoraDGetChildByName(self, "night")
	self.night:setVisible(false)
	self.guideManager:initData(self, self.startStep)
	if device.platform == "mac" or userSDKManager.isBeta() or userSDKManager.isGameDevelop() then
		_ENV = self.startStep
		self.startStep.guideManager = self.guideManager
		self.startStep.startStep = mainCityGuideStep
		uiManager:show("MainCityGuideTest", self.startStep)
	end
	uiManager:show("MainCityGuideUI")
	self.mainCityView.touchlayer:setTouchEnabled(false)
	self.mainCityView:setZoomScale(1.2)
	if not isNeedFirstFight then
		_UPVALUE1_ = self.startStep
		self.startStep[1] = cca.delay(0.1)
		self.startStep[2] = cca.callFunc(function()
			self:startGuide()
		end)
		self.startStep[3] = cca.callFunc(function()
			self:startGuide()
		end)
		self:runAction(cca.seq(self.startStep))
	end
end
function mainCityGuide:startGuide()
	SoraDCloseLoginView()
	self.guidingData = nil
	self.guideManager:startGuide(self.startStep)
end
function mainCityGuide:onMessageListener()
	SoraDAddMessage(self, "MESSAGE_MAINCITYGUIDE_STEPEND", handler(self, self.onStepEnd))
	SoraDAddMessage(self, "MESSAGE_MAINCITYGUIDE_CONTINUE", handler(self, self.onContinue))
	SoraDAddMessage(self, "MESSAGE_MAINCITYGUIDE_ROLETALK", handler(self, self.onRoleTalk))
	SoraDAddMessage(self, "MESSAGE_MAINCITYVIEW_FIRST_FIGHT_END", handler(self, self.startGuide))
	SoraDAddMessage(self, "MESSAGE_MAINSCEN_LOGINFINSH", handler(self, self.reLoginFinish))
end
function mainCityGuide:setGuidingData(guidingData)
	self.guidingData = guidingData
end
function mainCityGuide:onContinue(target, data)
	if self.guidingData and self.guidingData.sdkEvent then
		self:sdkEvent(self.guidingData.sdkEvent, true)
	end
end
function mainCityGuide:notifyStepEnd(param)
	if param ~= nil and type(param) == "table" and param.noNotify then
		return
	end
	_ENV = param
	param.msg = "MESSAGE_MAINCITYGUIDE_CONTINUE"
	SoraDSendMessage(param)
end
function mainCityGuide:prepareGuideData(param, noNotify)
	self.mainCityView.touchlayer:setTouchEnabled(false)
	self.guideManager:prepareGuideData(param)
	if not noNotify then
		self:notifyStepEnd()
	end
end
function mainCityGuide:showNode(param, noNotify)
	for i, v in ipairs(param) do
		local node = self.guideManager:getNode(v)
		if node then
			node:setVisible(true)
		else
			print("node not found", v)
		end
	end
