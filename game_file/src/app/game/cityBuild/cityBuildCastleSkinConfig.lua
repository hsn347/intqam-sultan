function cityBuildCastleSkinConfig.getCastleLvPos(model)
	local imgUpgradePos = cc.p(171, -6)
	local buildLvBgPos = cc.p(125, -33)
	local textLvPos = cc.p(146, -32)
	if not cityBuildCastleSkinConfig.tbSkinInfo[model] then
		local _ENV, config = cityBuildCastleSkinConfig.tbSkinInfo[model], cityBuildCastleSkinConfig.tbSkinInfo[model]
	end
	if config.lvBaseOffset then
		imgUpgradePos = cc.p(imgUpgradePos.x + config.lvBaseOffset.x, imgUpgradePos.y + config.lvBaseOffset.y)
		buildLvBgPos = cc.p(buildLvBgPos.x + config.lvBaseOffset.x, buildLvBgPos.y + config.lvBaseOffset.y)
		textLvPos = cc.p(textLvPos.x + config.lvBaseOffset.x, textLvPos.y + config.lvBaseOffset.y)
	end
	if config.new then
		return imgUpgradePos, buildLvBgPos, textLvPos
	else
		return cc.p(imgUpgradePos.x + 95, imgUpgradePos.y - 160), cc.p(buildLvBgPos.x + 95, buildLvBgPos.y - 160), cc.p(textLvPos.x + 95, textLvPos.y - 160)
	end
end
function cityBuildCastleSkinConfig.getSkinInfo(model)
	return cityBuildCastleSkinConfig.tbSkinInfo[model] or cityBuildCastleSkinConfig.tbSkinInfo[1]
end
function cityBuildCastleSkinConfig.getOwnTexture(model)
	return cityBuildCastleSkinConfig.tbSkinInfo[model] and cityBuildCastleSkinConfig.tbSkinInfo[model].ownTexture or 1
end
function cityBuildCastleSkinConfig.getSkinCsb(info)
	local csb = info.csb
	if SoraDGetFactionType() == FACTION_TYPE.FACTION_BYZANTINE then
		csb = info.csb_bzt or info.csb_ros or info.csb
	elseif SoraDFIsRA() then
		csb = info.csb
	else
		csb = info.csb_ros or info.csb
	end
	local targetCsb = string.format("ccsCommonFiles/castleSkin/%s.csb", csb)
	return targetCsb
end
function cityBuildCastleSkinConfig.getSkinOffset(info)
	local offset = cityBuildCastleSkinConfig.tbSkinInfo[1].offset
	if SoraDGetFactionType() == FACTION_TYPE.FACTION_BYZANTINE then
		offset = info.offset_bzt or info.offset_ros or info.offset
	elseif SoraDFIsRA() then
		offset = info.offset
	else
		offset = info.offset_ros or info.offset
	end
	return info.new and offset or cc.p(offset.x + 264, offset.y + 75)
end
function cityBuildCastleSkinConfig.getSkinNightCsb(info)
	local night = info.night
	if SoraDGetFactionType() == FACTION_TYPE.FACTION_BYZANTINE then
		night = info.night_bzt or info.night_ros or info.night
	elseif SoraDFIsRA() then
		night = info.night
	else
		night = info.night_ros or info.night
	end
	local targetNight = string.format("ccsCommonFiles/castleSkinNight/%s.csb", night)
	return targetNight
end
return cityBuildCastleSkinConfig
