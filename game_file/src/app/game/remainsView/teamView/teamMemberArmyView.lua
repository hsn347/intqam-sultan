local gametop = gModuleMgr.getObject("gametop")
local remainsTeamCtrl = gametop.playertop_:getModule("remainsTeamCtrl")
local remainsWarUtil = include("remainsWarUtil")
local remainsWarRead = include("remainsWarRead")
local teamMemberArmyView = class("teamMemberArmyView", function(target)
	if target == nil then
		return SoraDCreateTouchPanel("teamMemberArmyView")
	end
	return target
end)
function teamMemberArmyView:ctor()
	self.scaleActTarget = SoraDGetChildByName(self, "Center_Node")
	self.ccs_bg = SoraDGetExtendChildFromCCSByName(self, "CCS_commonPopBox_bg")
	self.ccs_bg:setTitleName(i18n("common_text_019"))
	self.scroll = SoraDGetChildByName(self, "ScrollView_army")
	self.txtName = SoraDGetChildByName(self, "Text_name")
	self.icon_head = SoraDGetChildByName(self, "icon_head")
	self.txtScoreNum = SoraDGetChildByName(self, "Text_score_num")
	self.txtLvNum = SoraDGetChildByName(self, "Text_lv_num")
	self:initCastleLvStarLvNode()
	self.labelOnline = SoraDGetChildByName(self, "Text_online")
	self.labelOnline:setString(i18n("common_text_224"))
	self.spScore = SoraDGetChildByName(self, "Sprite_score")
	self.nodeOnline = SoraDGetChildByName(self, "Node_onlne")
	self.spLeader = SoraDGetChildByName(self, "Sprite_leader")
	self.nodeSelf = SoraDGetChildByName(self, "Node_self")
	self.nodeOther = SoraDGetChildByName(self, "Node_other")
	self.txtCount = SoraDGetChildByName(self, "Text_armyCount")
	self.btnAdjust = SoraDGetChildByName(self, "Button_adjust")
	self.btnMemberRemove = SoraDGetChildByName(self, "Button_member_remove")
	self.btnMemberLeader = SoraDGetChildByName(self, "Button_member_leader")
	self.btnAdjust:addTouchEventListener(handler(self, self.onClick_btnAdjust))
	self.btnMemberRemove:addTouchEventListener(handler(self, self.onClick_btnMemberRemove))
	self.btnMemberLeader:addTouchEventListener(handler(self, self.onClick_btnMemberLeader))
	self.btnAdjust:setTitleText(i18n("remains_btn_14"))
	self.btnMemberRemove:setTitleText(i18n("remains_btn_13"))
	self.btnMemberLeader:setTitleText(i18n("remains_btn_12"))
	local isXianXia = remainsWarUtil.checkIsInRemainsXianXia()
	if isXianXia then
		self.btnMemberLeader:setVisible(false)
		self.btnMemberRemove:setPositionX(0)
	end
end
function teamMemberArmyView:initCastleLvStarLvNode(...)
	local node = SoraDCreatePanel("commonCastleLvStarLv")
	node:addTo(self.txtLvNum:getParent())
	node:setPosition(self.txtLvNum:getPositionX(), self.txtLvNum:getPositionY())
	node:setTextLvColor(self.txtLvNum:getColor())
	self.node_lv = node
	self.txtLvNum:setVisible(false)
end
function teamMemberArmyView:onMessageListener()
	SoraDAddMessage(self, "MESSAGE_SERVER_REMAINS_TEAM_MEMBER_INFO_BACK", handler(self, self.rspMemberInfo))
	SoraDAddMessage(self, "MESSAGE_SERVER_REMAINS_TEAM_MEMBER_EXPEL", handler(self, self.rspTeamOperator))
	SoraDAddMessage(self, "MESSAGE_SERVER_REMAINS_TEAM_LEADER_CHANGE", handler(self, self.rspTeamOperator))
	SoraDAddMessage(self, "MESSAGE_UI_TEAM_MY_INFO", handler(self, self.updateTeamInfo))
end
function teamMemberArmyView:initView(data, teamData)
	self:setTeamInfo(data, teamData)
	self:req4Data()
end
function teamMemberArmyView:initAnchorView(data)
	self:setTeamInfo(data)
	self.btnAdjust:setVisible(false)
	self.btnMemberRemove:setVisible(false)
	self.btnMemberLeader:setVisible(false)
end
