local buffDesRead = include("buffDesRead")
local godEquipmentGadSingle = class("godEquipmentGadSingle", function(luaFileName)
	return SoraDCreateBasePanel("godEquipmentGadSingle")
end)
function godEquipmentGadSingle:ctor()
	self.Image_base = SoraDGetChildByName(self, "Image_base")
	self.Node_icon = SoraDGetChildByName(self, "Node_icon")
	self.icon_base = SoraDGetChildByName(self.Node_icon, "icon_base")
	self.icon_attr = SoraDGetChildByName(self.Node_icon, "icon_attr")
	self.icon_fight_block = SoraDGetChildByName(self.Node_icon, "icon_fight_block")
	self.Text_attr = SoraDGetChildByName(self, "Text_attr")
	self.Text_attr_value = SoraDGetChildByName(self, "Text_attr_value")
	self.Text_power = SoraDGetChildByName(self, "Text_power")
	self.Text_power:setString(i18n("weapon_text_13"))
	self.Text_power_value = SoraDGetChildByName(self, "Text_power_value")
end
function godEquipmentGadSingle:initData(data)
	self.Text_attr:setString(data.buffName)
	self.Text_attr_value:setString(data.value)
	self.Text_power_value:setString(string.formatnumberthousands(data.power))
	self.icon_attr:setSpriteFrame(data.buffIcon)
	self.Image_base:setVisible(data.index % 2 == 1)
	self:setIconStatus(data.isReach)
end
function godEquipmentGadSingle:setIconStatus(isReach)
	local color = isReach and cc.c3b(255, 255, 255) or cc.c3b(100, 100, 100)
	self.icon_base:setColor(color)
	self.icon_attr:setColor(color)
	self.icon_fight_block:setVisible(not isReach)
	local labColor = isReach and cc.c3b(215, 195, 155) or cc.c3b(115, 115, 115)
	self.Text_power:setColor(labColor)
	self.Text_attr:setColor(labColor)
	self.Text_power_value:setColor(isReach and cc.c3b(0, 190, 30) or cc.c3b(115, 115, 115))
	self.Text_attr_value:setColor(isReach and cc.c3b(0, 190, 30) or cc.c3b(115, 115, 115))
end
return godEquipmentGadSingle
