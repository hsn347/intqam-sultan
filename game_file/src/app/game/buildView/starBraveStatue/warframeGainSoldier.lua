local armyDesRead = include("armyDesRead")
local warframeGainSoldier = class("warframeGainSoldier", function(target)
	if target and tolua.type(target) == "string" then
		target = SoraDCreateTouchPanel(target)
	end
	return target or SoraDCreateTouchPanel("warframeGainSoldier")
end)
function warframeGainSoldier:ctor(properties)
	self.Center_Node = SoraDGetChildByName(self, "Center_Node")
	self.nodeUsm1 = SoraDGetChildByName(self, "Node_usm1")
	self.imgSoldier = SoraDGetChildByName(self, "Image_1")
	self.imgSoldier:ignoreContentAdaptWithSize(true)
	self.imgSoldier:setScale(1.3)
	self.textNum = SoraDGetChildByName(self, "Text_Num")
	self.nodeUsm2 = SoraDGetChildByName(self, "Node_usm2")
	self.nodeUsm3 = SoraDGetChildByName(self, "Node_usm3")
	self.SpineNode = SoraDGetChildByName(self, "Node_Spine")
	self:initEffect()
end
function warframeGainSoldier:initEffect()
	local sp_jstc_001 = cc.criSprite.createCriSprite("sp_jstc_001.usm", false, true, handler(self, self.showSpine))
	sp_jstc_001:setAnchorPoint(cc.p(0.5, 0.5))
	sp_jstc_001:setCascadeOpacityEnabled(true)
	sp_jstc_001:setBlendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA)
	sp_jstc_001:addTo(self.nodeUsm1)
	sp_jstc_001:setPosition(0, 0)
	local sp_jstc_002 = cc.criSprite.createCriSprite("sp_jstc_002.usm", false, true, nil)
	sp_jstc_002:setAnchorPoint(cc.p(0.5, 0))
	sp_jstc_002:setBlendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA)
	sp_jstc_002:addTo(self.nodeUsm2)
	sp_jstc_002:setPosition(0, -display.cy)
	local sp_jstc_003 = cc.criSprite.createCriSprite(SoraDFIsRA() and "sp_jstc_003.usm" or "sp_jstc_004.usm", false, true, nil)
	sp_jstc_003:setAnchorPoint(cc.p(0.5, 0))
	sp_jstc_003:setBlendFunc(gl.SRC_ALPHA, gl.ONE_MINUS_SRC_ALPHA)
	sp_jstc_003:addTo(self.nodeUsm3)
	sp_jstc_003:setPosition(0, 0)
end
function warframeGainSoldier:initData(num, newArmyId)
	_ENV = nil
	;(nil).num1 = string.formatnumberthousands(num)
	;(nil).name1 = armyDesRead.getName(newArmyId)
	self.textNum:setString(i18n("Soldiers_armor_text_52", nil))
	local _, spine = armyDesRead.getSpecialArmyCfg(newArmyId, true)
	if spine then
		self.imgSoldier:setVisible(false)
		self.SpineNode:removeAllChildren()
		self.SpineNode:setScale(1.2)
		spine:addTo(self.SpineNode)
		spine:setAnimation(0, "animation", true)
		self.SpineNode:setVisible(true)
		spine:setPosition(cc.p(0, -200))
	else
		self.SpineNode:setVisible(false)
		self.imgSoldier:loadTexture(armyDesRead.getPortrait(newArmyId), ccui.TextureResType.plistType)
		self.imgSoldier:setVisible(true)
	end
	self.Center_Node:setOpacity(0)
end
function warframeGainSoldier:showSpine(criSp)
	criSp:start()
	self.Center_Node:setScale(0.0)
	_UPVALUE1_ = nil
	;(nil)[1] = cc.EaseBackOut:create(cca.scaleTo(0.3, 1))
	;(nil)[2] = cca.fadeTo(0.3, 1)
	;(nil)[3] = cca.fadeTo(0.3, 1)
	;(nil)[4] = cca.fadeTo(0.3, 1)
	;(nil)[5] = cca.fadeTo(0.3, 1)
	self.Center_Node:runAction(cca.spawn(nil))
end
return warframeGainSoldier
