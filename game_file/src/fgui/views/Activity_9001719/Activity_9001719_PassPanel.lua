local activity_9001719_Read = include("activity_9001719_Read")
local activity_9001719_Ctrl = SoraDGetCtrl("activity_9001719_Ctrl")
local baseFguiPanel = require("fgui.base.baseFguiPanel")
local Activity_9001719_PassPanel = class("Activity_9001719_PassPanel", baseFguiPanel)
function Activity_9001719_PassPanel:ctor(...)
	self.isLRU = true
	Activity_9001719_PassPanel.super.ctor(self, ...)
	print("Activity_9001719_PassPanel:ctor", self.viewName)
	self.activityID = gActivityTimeActivityID.MAGIC_CARPET
end
function Activity_9001719_PassPanel:onInit()
	print("=======Activity_9001719_PassPanel:onInit")
	self.fields.Com_bg:setGradientColor()
	self.fields.Com_title:initData(i18n("magic_carpet_02"), handler(self, self.onClickClose))
	self.fields.Text_tip:setString(i18n("balloon_hunter_014"))
	self.fields.Text_lv:setString(i18n("daily_salute_text21"))
	self.fields.Text_normal:setString(i18n("Braque_text_03"))
	self.fields.Text_adv:setString(i18n("Braque_text_05"))
	self.fields.Btn_unlock:setString(i18n("Braque_text_07"))
	self.fields.Btn_unlock:addClickListener(handler(self, self.btnUnlockClick))
	self.fields.Button_oneKey:setString(i18n("summoned_btn_01"))
	self.fields.Button_oneKey:addClickListener(handler(self, self.btnOneKeyClick))
	self.fields.List:setVirtual()
	self.fields.List:setItemRenderer(handler(self, self.onItemRenderer))
	self.fields.bg:fix()
	self.fields.Text_lv:fixPos()
	self.fields.Text_normal:fixPos()
	self.fields.Text_adv:fixPos()
	self.fields.Btn_unlock:fixPos()
	self.fields.line1:fixPos()
	self.fields.line2:fixPos()
	self.fields.shadow:fixPos()
end
function Activity_9001719_PassPanel:onItemRenderer(index, obj)
	obj:initData(self.lvList[index + 1])
end
function Activity_9001719_PassPanel:endShow()
	print("=======Activity_9001719_PassPanel:endShow")
	self.fields.Com_title:initCommonActivityTime(self.activityID)
	self.lvList = activity_9001719_Read.getBattlepassCfg()
	self:initView()
end
function Activity_9001719_PassPanel:initView()
	SoraDCloseLoading(self)
	self.fields.List:setNumItems(#self.lvList)
	local isUnlockAdv = activity_9001719_Ctrl:getUnlockAdv()
	self.fields.Btn_unlock:setVisible(not isUnlockAdv)
	self.fields.shadow:setVisible(not isUnlockAdv)
	self.isHaveReward = activity_9001719_Ctrl:isHaveSignReward()
	self.fields.Button_oneKey:setReddot(self.isHaveReward)
	self.fields.Button_oneKey:setEnabled(self.isHaveReward)
end
function Activity_9001719_PassPanel:btnUnlockClick()
	SoraDPlaySound()
	uiManager:show("Activity_9001719_BuyGift")
end
function Activity_9001719_PassPanel:btnOneKeyClick()
	SoraDPlaySound()
	activity_9001719_Ctrl:reqPassAllReward()
	SoraDShowLoading(self)
end
return Activity_9001719_PassPanel
