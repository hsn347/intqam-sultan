local baseProxy = require("fgui.base.baseProxy")
local ArenaMainViewProxy = class("ArenaMainViewProxy", baseProxy)
function ArenaMainViewProxy:onRegisterEvent()
	print("=======ArenaMainViewProxy:onRegisterEvent")
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_BATTLEINFO", handler(self, self.initData))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_REFRESHENEMY", handler(self, self.initEnemysData))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_GLOBALCHANGE", handler(self, self.judgeGlobalChange))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_SEEARMYINFO", handler(self, self.reqBackInfo))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_TIPCHANGE", handler(self, self.changeTip))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_FIGHTERR", handler(self, self.errTip))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_REFRESHTOPRANK", handler(self, self.refreshTopRank))
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_BUYSUCCESS", function(...)
		SoraDShowMsgTip(i18n("common_text_4293"))
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_MYINFOCHANGE", function(...)
		SoraDCloseLoading(self.view:displayObject())
		self.view:initHeadData()
		self.view:refreshHead()
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_CLOSELOADING", function(...)
		SoraDCloseLoading(self.view:displayObject())
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_RESULTBACK", function(...)
		SoraDCloseLoading(self.view:displayObject())
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_GROUPCHANGE", function(...)
		SoraDRemoveAllAfterPanelFromManager(self.view)
		SoraDShowMsgTip(i18n("mail_text_118"))
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_SETARMYLIST", function(...)
		SoraDCloseLoading(self.view:displayObject())
		self.view:initHeadData()
		self.view:refreshHead()
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_ARENA_REFRESH_BUFF", function(...)
		self.view:initData()
	end)
end
function ArenaMainViewProxy:initData(...)
	self.view:initData(...)
end
function ArenaMainViewProxy:initEnemysData(...)
	self.view:initEnemysData(...)
end
function ArenaMainViewProxy:judgeGlobalChange(...)
	self.view:judgeGlobalChange(...)
end
function ArenaMainViewProxy:reqBackInfo(...)
	self.view:reqBackInfo(...)
end
function ArenaMainViewProxy:changeTip(...)
	self.view:changeTip(...)
end
function ArenaMainViewProxy:errTip(...)
	self.view:errTip(...)
end
function ArenaMainViewProxy:refreshTopRank(...)
	self.view:refreshTopRank(...)
end
return ArenaMainViewProxy
