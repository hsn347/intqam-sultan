local baseProxy = require("fgui.base.baseProxy")
local treasureHuntMerchantPopProxy = class("treasureHuntMerchantPopProxy", baseProxy)
function treasureHuntMerchantPopProxy:onRegisterEvent()
	print("=======treasureHuntMerchantPopProxy:onRegisterEvent")
	SoraDAddMessage(self, "MESSAGE_ANNIVERSARY_TREASURE_HUNT_BUY_PACKAGE", function(target, data)
		SoraDCloseLoading()
		self.view:initData()
	end)
	SoraDAddMessage(self, "MESSAGE_ANNIVERSARY_TREASURE_HUNT_CANCEL_BUY_PACKAGE", function(target, data)
		SoraDCloseLoading()
		SoraDRemoveAllAfterPanelFromManager(self.view)
	end)
	SoraDAddMessage(self, "MESSAGE_SERVER_RECHARGECENTER_REFRESH", function(target, data)
		self.view:initData()
	end)
	SoraDAddMessage(self, "MESSAGE_RECHARGE_PRESENT_REFRESH_ACTIVE", handler(self, self.initView))
	SoraDAddMessage(self, "MESSAGE_ANNIVERSARY_TREASURE_HUNT_REFRESH_PACKAGE_STATE", function(target, data)
		SoraDCloseLoading()
		self.view:initData()
	end)
	SoraDAddMessage(self, "MESSAGE_RECHARGE_EXCHANGE_REFRESH", handler(self, self.initView))
end
function treasureHuntMerchantPopProxy:initView()
	self.view:updateScroll()
end
return treasureHuntMerchantPopProxy
