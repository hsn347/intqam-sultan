local baseProxy = require("fgui.base.baseProxy")
local ChatRoomInfoViewProxy = class("ChatRoomInfoViewProxy", baseProxy)
function ChatRoomInfoViewProxy:onRegisterEvent()
	print("=======ChatRoomInfoViewProxy:onRegisterEvent")
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_OPEN_SEL_PLAYERS", function(target, data)
		self.view:msgOpenSelPlayers(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_SERVER_GET_MEMBERS_SUCCESS", function(target, data)
		self.view:msgGetMembersSuccess(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_CLOSE_INFOVIEW", function(target, data)
		self.view:msgCloseInfoView(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_INFOVIEW_SHOW_LOADING", function(target, data)
		self.view:msgShowLoading(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_INFOVIEW_CLOSE_LOADING", function(target, data)
		self.view:msgCloseLoading(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_SERVER_QUIT_FAILED", function(target, data)
		self.view:sMsgQuitFailed(target, data)
	end)
	SoraDAddMessage(self, "MESSAGE_CHAT_ROOM_SERVER_QUIT_SUCCESS", function(target, data)
		self.view:sMsgQuitSuccess(target, data)
	end)
end
return ChatRoomInfoViewProxy
