local cityCtrl = SoraDGetCtrl("cityCtrl")
local baseComponent = require("fgui.base.baseComponent")
local Btn_res = fgui.extension_class(fgui.GButton, baseComponent)
fgui.register_extension("ui://MainUI/Btn_res", Btn_res)
function Btn_res:onInit()
	self.fields.Text_ani:setVisible(false)
	self:addClickListener(handler(self, self.onBtnClick))
	self.fields.icon:fixPos()
	self.fields.title:fixPos()
	self.fields.Text_ani:fixPos()
end
function Btn_res:onShow()
	self.fields.Text_ani:setVisible(false)
end
function Btn_res:initData(resID)
	self.resID = resID
	local val = cityCtrl:getResCount(self.resID)
	self.fields.title:setString(SoraDConvertNumberWithUnit(val))
	self.controllers.c2:setSelectedIndex(val > cityCtrl:getResMaxTotal() and 1 or 0)
end
function Btn_res:onBtnClick()
	if self.resID == gIDDef.METEOR_CRYSTAL then
		SoraDPlaySound("uicontrol", 23)
		_ENV = nil
		;(nil).rid = gIDDef.METEOR_CRYSTAL
		uiManager:show("meteorBuyView", nil)
	else
		if self.resID == gIDDef.MITHRIL then
			SoraDPlaySound("uicontrol", 27)
		elseif self.resID == gIDDef.IRON then
			SoraDPlaySound("uicontrol", 26)
		elseif self.resID == gIDDef.FOOD then
			SoraDPlaySound("uicontrol", 24)
		elseif self.resID == gIDDef.WOOD then
			SoraDPlaySound("uicontrol", 28)
		elseif self.resID == gIDDef.CRYSTAL then
			SoraDPlaySound("uicontrol", 23)
		end
		_ENV = nil
		;(nil).rid = self.resID
		uiManager:show("resourceBuyView", nil)
	end
end
